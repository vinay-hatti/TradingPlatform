import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
const root=process.env.TARGET_ROOT||process.cwd();
const pages=fs.readFileSync(path.join(root,'src/pages.tsx'),'utf8');
const css=fs.readFileSync(path.join(root,'src/styles.css'),'utf8');
test('compact strategy selector replaces card wall',()=>{assert.match(pages,/strategy-selector-compact/);assert.match(pages,/value=\{strategy\}/);});
test('filters collapse by default',()=>{assert.match(pages,/scannerControlsOpen/);assert.match(pages,/controls-collapsed/);});
test('operational details are progressive disclosure',()=>{assert.match(pages,/scanner-operational-details/);});
test('scanner remains persisted-only',()=>{assert.match(pages,/refresh_mode:persistedOnly\?'cache_only'/);assert.match(pages,/auto_refresh:persistedOnly\?false/);});
test('route-local CSS is present',()=>{assert.match(css,/UI Maintenance Patch 2/);assert.match(css,/\.option-scanner-workspace \.candidate-table-scroll/);});
