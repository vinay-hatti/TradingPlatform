from sqlalchemy import JSON, Float, Integer, String, Text, UniqueConstraint
from sqlalchemy.orm import Mapped, mapped_column
from trading_ai.database.base import Base
class TradePlanModel(Base):
    __tablename__='advanced_trade_plans'
    __table_args__=(UniqueConstraint('opportunity_id','opportunity_version','account_id','strategy',name='uq_m56_trade_plan_source'),)
    trade_plan_id:Mapped[str]=mapped_column(String(128),primary_key=True)
    opportunity_id:Mapped[str]=mapped_column(String(128),nullable=False,index=True)
    opportunity_version:Mapped[int]=mapped_column(Integer,nullable=False)
    intelligence_id:Mapped[str|None]=mapped_column(String(128))
    account_id:Mapped[str]=mapped_column(String(128),nullable=False,index=True)
    symbol:Mapped[str]=mapped_column(String(32),nullable=False,index=True)
    direction:Mapped[str]=mapped_column(String(16),nullable=False)
    strategy:Mapped[str]=mapped_column(String(64),nullable=False,index=True)
    state:Mapped[str]=mapped_column(String(32),nullable=False,index=True)
    version:Mapped[int]=mapped_column(Integer,nullable=False,default=1)
    capital:Mapped[float]=mapped_column(Float,nullable=False)
    risk_budget_pct:Mapped[float]=mapped_column(Float,nullable=False)
    risk_budget_amount:Mapped[float]=mapped_column(Float,nullable=False)
    estimated_debit:Mapped[float]=mapped_column(Float,nullable=False)
    estimated_credit:Mapped[float]=mapped_column(Float,nullable=False)
    max_loss:Mapped[float]=mapped_column(Float,nullable=False)
    max_profit:Mapped[float|None]=mapped_column(Float)
    reward_risk_ratio:Mapped[float|None]=mapped_column(Float)
    net_greeks_json:Mapped[dict]=mapped_column(JSON,nullable=False)
    validation_json:Mapped[dict]=mapped_column(JSON,nullable=False)
    legs_json:Mapped[list]=mapped_column(JSON,nullable=False)
    execution_intent_json:Mapped[dict]=mapped_column(JSON,nullable=False,default=dict)
    notes:Mapped[str]=mapped_column(Text,nullable=False,default='')
    created_by:Mapped[str]=mapped_column(String(128),nullable=False)
    created_at:Mapped[str]=mapped_column(String(64),nullable=False,index=True)
    updated_at:Mapped[str]=mapped_column(String(64),nullable=False)
